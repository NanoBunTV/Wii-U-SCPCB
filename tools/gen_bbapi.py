"""Generates the Blitz command API description from the runtime sources.

Every Blitz command is registered in a *_link() function as  rtSym( "Signature",cppFunction ).
The signature string encodes the Blitz name, return type and parameters (with defaults), e.g.
    "%LoadTexture$file%flags=1"   ->  LoadTexture( file$, flags% = 1 ) returns an int handle

Outputs
  runtime/bbruntime/bbapi.h   C++ declarations of every command function (for transpiled code / tests)
  tools/bbapi.json            per command : Blitz name, return type, parameters, defaults, C++ function,
                              C++ return / parameter types (used by the BlitzBasic -> C++ transpiler)

Usage :  python tools/gen_bbapi.py        (run from the project root)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIRS = ['runtime/bbruntime']

SYM_RE = re.compile(r'rtSym\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*(?:\(void\*\))?\s*(\w+)\s*\)')
BLITZ_TYPES = {'%': 'int', '#': 'float', '$': 'string'}


def parse_signature(sig):
    sig = sig.encode().decode('unicode_escape')
    ret = 'void'
    if sig and sig[0] in '%#$':
        ret = BLITZ_TYPES[sig[0]]
        sig = sig[1:]
    m = re.match(r'([A-Za-z_]\w*)(.*)', sig)
    name, rest = m.group(1), m.group(2)
    params = []
    # parameters : <type char><name>[=<default>] ; defaults may be quoted strings
    for pm in re.finditer(r'([%#$])(\w+)(?:=("(?:[^"]*)"|[^%#$]*))?', rest):
        default = pm.group(3)
        params.append({'type': BLITZ_TYPES[pm.group(1)], 'name': pm.group(2), 'default': default})
    return name, ret, params


def find_definition(text, fn):
    # return type (one or more tokens, possibly with *), the function name, the parameter list, then '{'
    m = re.search(r'(?m)^[ \t]*((?:const\s+)?[\w:]+(?:\s*\*+)?(?:\s+[\w:]+)*\s*\*?)\s*\b' + re.escape(fn)
                  + r'\s*\(([^)]*)\)\s*\{', text)
    if not m:
        return None
    ret = ' '.join(m.group(1).replace('static', '').split())
    params = [' '.join(p.split()) for p in m.group(2).split(',') if p.strip() and p.strip() != 'void']
    return ret, params


def main():
    commands = []
    decls = []
    types = set()
    missing = []
    for d in SRC_DIRS:
        for fname in sorted(os.listdir(os.path.join(ROOT, d))):
            if not fname.endswith('.cpp'):
                continue
            text = open(os.path.join(ROOT, d, fname), encoding='latin-1').read()
            for sig, fn in SYM_RE.findall(text):
                name, ret, params = parse_signature(sig)
                if name.startswith('_bb'):
                    continue            # compiler intrinsics, declared in basic.h / userlibs.h
                defn = find_definition(text, fn)
                if not defn:
                    missing.append('%s (%s in %s)' % (name, fn, fname))
                    continue
                cret, cparams = defn
                ctypes = []
                for p in cparams:
                    m2 = re.match(r'^(.*?[\s\*&])(\w+)$', p)     # "type name" / "type *name" -> type
                    ctypes.append(' '.join(m2.group(1).split()) if m2 and m2.group(1).strip() else p)
                for t in [cret] + ctypes:
                    base = t.replace('const', '').replace('*', '').strip()
                    if base not in ('int', 'float', 'void', 'char', 'unsigned', 'bool', 'BBStr'):
                        types.add(base)
                static = re.search(r'(?m)^[ \t]*static\b[^\n]*\b' + re.escape(fn) + r'\s*\(', text) is not None
                commands.append({
                    'sig': sig.encode().decode('unicode_escape'),
                    'name': name, 'ret': ret, 'params': params,
                    'cpp': fn, 'cpp_ret': cret, 'cpp_params': ctypes, 'file': fname, 'static': static,
                })
                if not static:
                    decls.append('%s %s( %s );' % (cret, fn, ','.join(ctypes)))

    out_h = os.path.join(ROOT, 'runtime/bbruntime/bbapi.h')
    with open(out_h, 'w') as f:
        f.write('// GENERATED by tools/gen_bbapi.py from the runtime sources -- do not edit.\n')
        f.write('// C++ declarations of the Blitz commands (the functions registered with rtSym).\n')
        f.write('#ifndef BBAPI_H\n#define BBAPI_H\n\n#include "basic.h"\n\n')
        for t in sorted(types):
            kw = 'struct' if t.startswith('bb') or t.startswith('BB') else 'class'
            f.write('%s %s;\n' % (kw, t))
        f.write('\n')
        for dcl in decls:
            f.write(dcl + '\n')
        f.write('\n#endif\n')

    out_j = os.path.join(ROOT, 'tools/bbapi.json')
    with open(out_j, 'w') as f:
        json.dump(commands, f, indent=1)

    # same data for tools/bb2cpp : one command per line,
    # <rtSym signature> TAB <C++ function> TAB <C++ return type> TAB <C++ parameter types, ';' separated>
    out_t = os.path.join(ROOT, 'tools/bbapi.txt')
    with open(out_t, 'w', newline='\n') as f:
        for c in commands:
            f.write('%s\t%s\t%s\t%s\n' % (c['sig'], c['cpp'], c['cpp_ret'], ';'.join(c['cpp_params'])))

    print('%d commands, %d declared in bbapi.h, %d static, %d missing definitions'
          % (len(commands), len(decls), sum(c['static'] for c in commands), len(missing)))
    for m in missing:
        print('  missing:', m)


if __name__ == '__main__':
    sys.exit(main())
